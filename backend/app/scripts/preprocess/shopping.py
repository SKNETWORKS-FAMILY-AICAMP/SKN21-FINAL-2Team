def _clean_nulls(data: list[dict]) -> list[dict]:
    """null/빈값 필드 제거"""
    for item in data:
        keys = [k for k, v in item.items() if v is None or v == ""]
        for k in keys:
            del item[k]
    return data


def _save(data: list[dict], path: Path):
    data = _clean_nulls(data)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"  → 저장: {path} ({len(data)}건)")


