def _oy_get_area_key(store: dict) -> str:
    title, addr = store["title"], store.get("addr", "")
    tags = store.get("tags", [])
    for key in OY_AREA_CONTEXT:
        if key in title or key in addr:
            return key
    tag_map = {
        "종각역": "종각", "종로": "종로", "광화문": "광화문",
        "안국역": "안국", "경복궁": "경복궁", "대학로": "대학로",
        "홍대": "홍대", "강남": "강남", "잠실": "잠실",
        "성수동": "성수", "성수": "성수", "명동": "명동",
    }
    for tag in tags:
        for k, v in tag_map.items():
            if k in tag:
                return v
    return ""


def _oy_generate_intro(store: dict) -> str:
    title = store["title"]
    addr = store.get("addr", "")
    area_ctx = OY_AREA_CONTEXT.get(_oy_get_area_key(store), "")
    intro = (
        f"{title}은 {addr.split('(')[0].strip()}에 위치한 올리브영 매장입니다. "
        f"K-뷰티 인기 브랜드의 스킨케어, 메이크업, 헤어·바디케어 등 다양한 뷰티 제품을 직접 테스트하고 구매할 수 있습니다. "
    )
    if area_ctx:
        intro += area_ctx + " "
    intro += "Visa, Mastercard 등 해외 결제를 지원하며 면세 쇼핑도 가능하여 외국인 관광객도 편리하게 이용할 수 있습니다."
    return intro


