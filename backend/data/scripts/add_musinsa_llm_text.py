def build_llm_text(item: dict, intro: str) -> str:
    """기존 build_llm_text.py와 동일한 형식으로 생성"""
    lines = []
    if title := item.get("title"):
        lines.append(f"- 장소명: {title}")
    if addr := item.get("addr"):
        lines.append(f"- 주소: {addr}")
    if v := item.get("usetime"):
        lines.append(f"- 영업시간: {v}")
    tags = item.get("tags") or []
    if tags:
        lines.append(f"- 주요 키워드: {', '.join(tags)}")
    if intro:
        lines.append(f"- 소개: {intro}")
    return "\n".join(lines)


def main():
    with open(DATA_PATH, encoding="utf-8") as f:
        stores = json.load(f)

    print(f"▶ {len(stores)}개 매장에 llm_text 추가...")

    updated = 0
    for store in stores:
        title = store["title"]
        intro = STORE_INTROS.get(title, "")

        if not intro:
            print(f"  ✗ 소개 없음: {title}")
            # fallback: summary 사용
            intro = store.get("summary", "")

        store["llm_text"] = build_llm_text(store, intro)
        updated += 1
        print(f"  ✓ {title} ({len(store['llm_text'])}자)")

    with open(DATA_PATH, "w", encoding="utf-8") as f:
        json.dump(stores, f, ensure_ascii=False, indent=2)

    print(f"\n✅ 완료! {updated}개 매장 llm_text 추가 → {DATA_PATH}")


if __name__ == "__main__":
    main()
